def serves_urban_pool(text: str) -> bool:
    """只有明确的都市超凡请求进入都市池。长篇本身不够。"""
    raw = (text or "").strip()
    if not raw:
        return False
    if raw in _URBAN_GENRES:
        return True
    if (
        _ABILITY_MARK.search(raw)
        or _POOL_MARK.search(raw)
        or _PLAIN_URBAN_MARK.search(raw)
    ):
        return True
    from app.writing.work_reconstruction import genre_of

    label = genre_of(raw)
    if label in _URBAN_GENRES:
        return True
    return bool(_URBAN_MARK.search(raw) and _POWER_MARK.search(raw))


def _preferred_shelves(text: str) -> set[str]:
    """只缩小抽取范围，不把分类写进题材或 prompt。"""
    if _HARD_MARTIAL_MARK.search(text):
        return {"异途武道", "个人面板"}
    if _SOLE_POWER_MARK.search(text):
        return {"独有异能", "个人面板", "都市生活"}
    if _RULE_POWER_MARK.search(text):
        return {"规则能力", "公开超凡", "游戏冒险"}
    if _SYSTEM_MARK.search(text):
        return {
            "个人面板",
            "异途武道",
            "公开超凡",
            "末世生存",
            "游戏冒险",
            "现代人生",
        }
    if _ABILITY_MARK.search(text):
        return {
            "都市隐秘",
            "公开超凡",
            "都市异变",
            "末世生存",
            "规则能力",
            "个人面板",
            "异途武道",
        }
    if _PLAIN_URBAN_MARK.search(text):
        return {"现代人生", "都市生活", "都市隐秘", "都市异变"}
    return set()


def uses_reference_pool(text: str) -> bool:
    """题材池只补充宽泛请求；用户已给出具体方向时不再塞入随机作品。"""
    raw = (text or "").strip()
    return serves_urban_pool(raw) and not _DIRECTED_REQUEST_MARK.search(raw)


def request_is_long_novel(text: str) -> bool:
    from app.writing.book_scope import explicit_book_scope, infer_book_scope

    named = explicit_book_scope(text)
    if named == "long":
        return True
    if named in {"short", "single"}:
        return False
    return infer_book_scope(text) == "long"


def select_seeds(
    text: str,
    k: int = 2,
    *,
    exclude_texts: Collection[str] = (),
    exclude_families: Collection[str] = (),
) -> list[SubjectSeed]:
    """从不同书架抽取完整题材；书架名不会进入生成上下文。"""
    if k <= 0 or not uses_reference_pool(text):
        return []
    blocked_texts = set(exclude_texts)
    blocked_shelves = set(exclude_families)
    preferred = _preferred_shelves(text)
    available = [
        seed
        for seed in _URBAN_SEEDS
        if seed.text not in blocked_texts and seed.shelf not in blocked_shelves
        and (not preferred or seed.shelf in preferred)
    ]
    by_shelf: dict[str, list[SubjectSeed]] = {}
    for seed in available:
        by_shelf.setdefault(seed.shelf, []).append(seed)
    if len(by_shelf) < k:
        return []
    shelves = random.sample(list(by_shelf), k)
    return [random.choice(by_shelf[shelf]) for shelf in shelves]


def pool_for(genre: str, *, user_text: str = "") -> tuple[str, ...]:
    probe = (user_text or genre or "").strip()
    if not serves_urban_pool(probe):
        return ()
    return tuple(seed.text for seed in _URBAN_SEEDS)


def family_of(text: str) -> str:
    """兼容旧诊断名；返回的是抽样书架，不是故事结构。"""
    for seed in _URBAN_SEEDS:
        if seed.text == text:
            return seed.shelf
    return ""


def draw_subjects(genre: str, k: int = 2, *, user_text: str = "") -> list[str]:
    probe = (user_text or genre or "").strip()
    return [seed.text for seed in select_seeds(probe, k)]
