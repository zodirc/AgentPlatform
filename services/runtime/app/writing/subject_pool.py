def pool_for(genre: str) -> tuple[str, ...]:
    key = (genre or "").strip()
    if key in _URBAN_GENRES:
        return _URBAN_WORLDS
    return ()


def draw_subjects(genre: str, k: int = 2) -> list[str]:
    """从该类型的题材里无放回均匀抽 k 条。没有这份池子就不抽。"""
    pool = pool_for(genre)
    if len(pool) < k:
        return []
    return random.sample(list(pool), k)
